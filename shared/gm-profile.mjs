export const campaignDeathPolicies = Object.freeze({
  classic: 'Как раньше · поражение в бою',
  replace: 'Продолжить с другим героем',
  end: 'Завершить кампанию при гибели героя'
});

export function normalizeGmSettings(value = {}) {
  const input = value && typeof value === 'object' ? value : {};
  return {
    profile: Object.hasOwn(gmProfiles, input.profile) ? input.profile : 'standard',
    deathPolicy: Object.hasOwn(campaignDeathPolicies, input.deathPolicy) ? input.deathPolicy : 'classic'
  };
}
