const loreByStart = {
  school: jujutsuSchoolLore,
  'night-city': edgerunnersNightCityLore,
  iceland: vinlandIcelandLore,
  ...saoLoreByStart
};

export function buildFanficStarter(starterId, startId, {originalPersona, canonCharacter, loreLanguage = 'ru'} = {}) {
  const starter = fanficStarters.find(candidate => candidate.id === starterId);
  const start = starter?.starts.find(candidate => candidate.id === startId);
  if (!starter || !start) throw new Error('Выберите стартовую сцену.');
  const {rules, beat} = scenes[start.id];
  const startKey=starter.id+'-'+start.id;
  const supportLore=fanficSupportLore[start.id].map(({id,cast,reference,keys,...entry})=>({
    ...entry,id:startKey+'-cast-'+id,
    keys:[...new Set([...cast.flatMap(member=>[starter.cast[member].name,...(starter.cast[member].aliases||[])]),...keys])]
  }));
  const characters = start.cast.map(id => {
    const card = starter.cast[id];
    const cardId=starter.id+'-'+id;
    const ruralAlice=start.id==='alicization'&&id==='alice';
    const scenario=start.support[id]||(ruralAlice?'На линии Рулида Алиса известна как подруга детства и сестра Сельки. Начни с доступного ей воспоминания или события; не назначай ранг до развития этой истории.':'');
    return {id:cardId,...card,description:card.subtitle,avatar:fanficTemplatePortrait(cardId,start.id),
      ...(ruralAlice?{appearance:'Светлые косы и голубые глаза. В детстве в Рулиде носит простое бело-голубое платье.'}:{}),
      ...(scenario?{scenario}:{})};
  });
  const canonLead = characters.find(character => character.id === canonCharacter);
  if (canonCharacter && !canonLead) throw new Error('Выберите героя этой точки старта.');
  if (originalPersona && canonLead) throw new Error('Выберите одну точку зрения.');
  const lead = originalPersona || canonLead;
  const loreEntries = [
    {name:'Точка старта', content:start.setup, priority:24, keys:['точка старта','начальные условия','starting point','opening conditions']},
    {name:'Условия выбранной ветки', content:rules, constant:true, priority:30, keys:[]},
    ...[...loreByStart[start.id],...fanficWorldLore[starter.id].map(({reference,...entry})=>entry),...supportLore]
      .map(entry=>({priority:15,...entry,vectorWhenMemory:true}))
  ].map((entry, index) => ({id:startKey+'-'+index, enabled:true, ...entry}));
  const opening = lead
    ? 'Веди сцену через восприятие «' + lead.name + '». Начни там, где этот герой мог находиться.' + (canonLead?.scenario?' '+canonLead.scenario:'')
    : 'Один наблюдатель на сцену. Герои по очереди проявляют инициативу.';
  const setup=canonLead?.scenario
    ? [opening,'Общая завязка ветки: '+start.setup,'Покажи первое действие выбранного героя там, где он находится. Подключай остальные линии через события и установленные каналы связи.']
    : [beat,opening];
  return {
    title: starter.title + ' · ' + start.label,
    world: starter.world,
    canon: start.setup + '\n\n' + rules,
    divergence: start.pivot,
    characters: characters.filter(character => character !== canonLead),
    personas: lead ? [lead] : [],
    lorebooks: [{id:starter.id + '-' + start.id, name: starter.title, language:loreLanguage==='en'?'en':'ru', entries:loreEntries}],
    settings: {
      genre: starter.label,
      style: worldStyles[starter.id],
      sceneCount: 2,
      instructions: [
        opening,
        'Веди оригинальную ветку без цитат и пересказа. Будущие события источника открыты до подтверждения каноном произведения.'
      ].join(' ')
    },
    episodes: [{season:start.season, number:1, title:start.label, brief:[...setup, 'Возможности развилки: '+start.pivot].join('\n\n')}]
  };
}
